        {
            0x93, 0x23, 0x6B, 0xAE, 0x2C, 0x2A, 0x31, 0xB6, 0x8F, 0xC4, 0x61, 0x88,
            0x93, 0xF2, 0x8C, 0x5D, 0x0F, 0xAD, 0x13, 0x98, 0xC0, 0x3D, 0x37, 0x98
        };

        internal static string D(byte[] d)
        {
            int n = d.Length;
            byte[] b = new byte[n];
            int kl = K.Length;
            for (int i = 0; i < n; i++)
            {
                b[i] = (byte)(d[i] ^ K[i % kl] ^ (byte)(i * 7 + 3));
            }
            return Encoding.UTF8.GetString(b);
        }

